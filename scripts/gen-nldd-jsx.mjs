// Writes JSX typings for every nldd-* element from the custom-elements.json in
// the installed package, so tsc catches an unknown tag or attribute.
// Boolean attributes accept only `true` or `undefined`: React 18 writes `false`
// as the string "false" on a custom element, and the component reads any value
// as on. Write `disabled={busy || undefined}`.
import { readFileSync, writeFileSync } from 'node:fs';

const pkgDir = new URL('../node_modules/@nldd/design-system/', import.meta.url);
const manifestPath = new URL('custom-elements.json', pkgDir);
const { version } = JSON.parse(readFileSync(new URL('package.json', pkgDir), 'utf8'));
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const literalUnion = /^\s*('[^']*'\s*\|\s*)*'[^']*'\s*$/;

function tsType(attr) {
  const t = (attr.expandedType?.text ?? attr.type?.text ?? 'string').trim();
  if (t === 'boolean' || t === 'boolean | undefined') return 'true | undefined';
  if (t === 'number') return 'number | string';
  if (/^[\d|\s]+$/.test(t)) return `${t} | \`${t.split('|').map((s) => s.trim()).join('` | `')}\``;
  if (literalUnion.test(t)) return t;
  return 'string';
}

const elements = [];
for (const mod of manifest.modules) {
  for (const dec of mod.declarations ?? []) {
    if (!dec.tagName?.startsWith('nldd-')) continue;
    const attrs = new Map();
    for (const a of dec.attributes ?? []) attrs.set(a.name, tsType(a));
    elements.push([dec.tagName, attrs]);
  }
}
elements.sort(([a], [b]) => a.localeCompare(b));

const body = elements
  .map(([tag, attrs]) => {
    const props = [...attrs].map(([n, t]) => `      '${n}'?: ${t};`).join('\n');
    return `    '${tag}': NlddBase & {\n${props}\n    };`;
  })
  .join('\n');

const out = `// Generated by scripts/gen-nldd-jsx.mjs from @nldd/design-system ${version}. Do not edit.
import type { DetailedHTMLProps, HTMLAttributes } from 'react';

type NlddBase = Omit<
  DetailedHTMLProps<HTMLAttributes<HTMLElement>, HTMLElement>,
  'color' | 'title' | 'hidden' | 'translate' | 'onChange' | 'onInput'
> & { class?: string; slot?: string };

declare module 'react' {
  // eslint-disable-next-line @typescript-eslint/no-namespace
  namespace JSX {
    interface IntrinsicElements {
${body}
    }
  }
}
`;
writeFileSync(new URL('../src/types/nldd-jsx.generated.d.ts', import.meta.url), out);
console.log(`nldd-jsx: ${elements.length} elements from ${version}`);
